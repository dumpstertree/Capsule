#!/bin/bash
# =============================================================================
# Capsule stream launcher — SWAY (Wayland) flavor. Started by
# capsule@<user>.service when capsule.config contains "TYPE=sway"
# (start-stream.sh routes here). Experimental: see README "Sway game capsule".
#
# Why: an X dummy display can never present hardware Vulkan (its swapchain
# needs DRI3 -> KMS -> DRM master, held by the GPU-backed capsule). A Wayland
# compositor has no such wall: apps render on a DRM *render node* (the RX
# 6800, no master required) and present via Wayland dmabufs. sway runs with
# the wlroots HEADLESS backend — no monitor, no KMS, no DRM master — while
# compositing fully on the GPU via WLR_RENDER_DRM_DEVICE. Sunshine captures
# it with its wlr backend (wlr-screencopy-unstable-v1).
#
# Chain:  steam (Xwayland) / native VK games (Wayland WSI)
#           -> sway headless output HEADLESS-1 (composited on render node)
#           -> Sunshine capture=wlr -> Moonlight
#
# Steam is launched through sway's own `exec` so it receives sway's DISPLAY
# (Xwayland) and XAUTHORITY; Sunshine is launched with XDG_SEAT re-set to the
# capsule's seat so its virtual devices keep the "(seatN)" naming used by
# input isolation. sway itself runs WITHOUT XDG_SEAT (libseat would try to
# bind a logind seat that does not exist in this container).
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

USERNAME="$(whoami)"
USER_HOME="$(capsule_user_home "$USERNAME")"
export PATH="$USER_HOME/.local/bin:$PATH"

INDEX="$(capsule_read_user_index "$USER_HOME/capsule.config")" \
    || error "Missing or invalid $USER_HOME/capsule.config"

# --- Config ---------------------------------------------------------------------
RENDER_NODE="$(capsule_conf_get CAPSULE_RENDER_NODE /dev/dri/renderD128)"
RESOLUTION="$(capsule_conf_get SWAY_RESOLUTION 1920x1080)"
REFRESH="$(capsule_conf_get SWAY_REFRESH 60)"
XDISPLAY="$(capsule_conf_get SWAY_XDISPLAY :10)"
SEAT="seat$((INDEX + 1))"

# --- Session environment ----------------------------------------------------------
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
if [ -z "${DBUS_SESSION_BUS_ADDRESS:-}" ]; then
    if [ ! -S "$XDG_RUNTIME_DIR/bus" ]; then
        error "No dbus session found. Run inside the capsule service (dbus-user-session)."
    fi
    export DBUS_SESSION_BUS_ADDRESS="unix:path=$XDG_RUNTIME_DIR/bus"
fi

export XDG_SESSION_TYPE=wayland
export XDG_CURRENT_DESKTOP=sway
unset XDG_SEAT                     # sway/libseat: no logind seat in here
export DISPLAY="$XDISPLAY"         # wlroots registers Xwayland under this

export WLR_BACKENDS=headless       # no KMS at all — the point of this design
export WLR_RENDER_DRM_DEVICE="$RENDER_NODE"   # composite on the RX 6800
export WLR_LIBINPUT_NO_DEVICES=1   # boot without inputs; Sunshine's uinput
                                   # devices hot-plug in once a stream starts
# Deliberately NOT setting WLR_RENDERER_ALLOW_SOFTWARE: if the render node is
# wrong/unusable, sway must fail loudly, not silently llvmpipe (that is the
# failure mode we are replacing).

command -v sway >/dev/null 2>&1 || \
    error "sway not found — install with: pacman -S sway"

if pgrep -U "$(id -u)" -x sway >/dev/null 2>&1; then
    echo "sway already running for $USERNAME (pid $(pgrep -U "$(id -u)" -x sway | head -1)). Exiting."
    exit 0
fi

if [ ! -e "$RENDER_NODE" ]; then
    error "Render node $RENDER_NODE missing — check CAPSULE_RENDER_NODE / LXC /dev/dri passthrough"
fi

# --- Save sync + game import (shared with the X flavor) -----------------------------
capsule_game_bootstrap "$SCRIPT_DIR" "$USERNAME" "$USER_HOME"

# --- Generate sway config ------------------------------------------------------------
SWAY_CONFIG="$USER_HOME/.config/sway/capsule.conf"
mkdir -p "$(dirname "$SWAY_CONFIG")"
cat > "$SWAY_CONFIG" <<EOF
# GENERATED by start-sway.sh — tune via /etc/capsule/config
# (SWAY_RESOLUTION, SWAY_REFRESH, SWAY_XDISPLAY, CAPSULE_RENDER_NODE).
output HEADLESS-1 resolution ${RESOLUTION}@${REFRESH}
default_border none
default_floating_border none
seat * hide_cursor never
xwayland enable
# Steam via sway's own exec: inherits sway's DISPLAY (Xwayland) + XAUTHORITY.
exec sh "$SCRIPT_DIR/inject.sh"
EOF
chown "$USERNAME:$USERNAME" "$SWAY_CONFIG" 2>/dev/null || true

# --- Start sway ------------------------------------------------------------------------
echo "Starting sway (headless, render node $RENDER_NODE, output ${RESOLUTION}@${REFRESH})"
sway --config "$SWAY_CONFIG" &
SWAY_PID=$!
SUNSHINE_PID=""

cleanup() {
    kill "$SUNSHINE_PID" "$SWAY_PID" 2>/dev/null || true
}
trap cleanup EXIT TERM INT

# Wait for sway's Wayland socket (sunshine needs WAYLAND_DISPLAY).
WAYLAND_DISPLAY=""
for _ in $(seq 1 50); do
    kill -0 "$SWAY_PID" 2>/dev/null || error "sway died during startup — see journal (-u capsule@$USERNAME)"
    for sock in "$XDG_RUNTIME_DIR"/wayland-*; do
        [ -S "$sock" ] || continue
        WAYLAND_DISPLAY="$(basename "$sock")"
        break
    done
    [ -n "$WAYLAND_DISPLAY" ] && break
    sleep 0.2
done
[ -n "$WAYLAND_DISPLAY" ] || error "sway did not create a Wayland socket within 10s"
export WAYLAND_DISPLAY
export SWAYSOCK="${SWAYSOCK:-$XDG_RUNTIME_DIR/sway-$(id -u).sock}"

# --- Sunshine in capture=wlr mode, foreground-tracked -------------------------------------
command -v sunshine >/dev/null 2>&1 || error "sunshine not found"
grep -qs '^capture *= *wlr' "$USER_HOME/.config/sunshine/sunshine.conf" || \
    warn "sunshine.conf lacks 'capture = wlr' — run preconfig-sway.sh $USERNAME"

echo "Starting Sunshine (wlr capture of $WAYLAND_DISPLAY; Moonlight UI: https://<this-host>:$(capsule_sunshine_ui_port "$INDEX"))"
env XDG_SEAT="$SEAT" sunshine &
SUNSHINE_PID=$!

# Unit lifetime = sway AND sunshine; whichever dies first ends the session
# (systemd restarts the pair cleanly).
while kill -0 "$SWAY_PID" 2>/dev/null && kill -0 "$SUNSHINE_PID" 2>/dev/null; do
    sleep 2
done
STATUS=0
kill -0 "$SUNSHINE_PID" 2>/dev/null || STATUS=1
echo "sway/sunshine session ended (sway alive: $(kill -0 "$SWAY_PID" 2>/dev/null && echo yes || echo no))"
exit "$STATUS"
