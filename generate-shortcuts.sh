#!/bin/bash
set -e

###############################################################################
# CONFIG
###############################################################################

VENV_DIR="/opt/capsule-steam-venv"
PYTHON_SCRIPT="/Capsule/generate-shortcuts.py"

###############################################################################
# VALIDATION
###############################################################################

if [[ "$(id -u)" -ne 0 ]]; then
    echo "Must be run as root"
    exit 1
fi

###############################################################################
# INSTALL PACKAGES
###############################################################################

echo "Installing packages..."

pacman -Sy --noconfirm \
    python \
    python-pip \
    python-virtualenv \
    git

###############################################################################
# CREATE VENV
###############################################################################

if [[ ! -d "$VENV_DIR" ]]; then
    echo "Creating venv..."
    python -m venv "$VENV_DIR"
fi

source "$VENV_DIR/bin/activate"

###############################################################################
# INSTALL PYTHON LIBRARIES
###############################################################################

echo "Installing python libraries..."

pip install --upgrade pip
pip install \
    vdf \
    requests \
    rapidfuzz \
    pillow

###############################################################################
# STOP STEAM
###############################################################################

echo "Stopping Steam..."

pkill steam || true
pkill steamwebhelper || true

sleep 2

###############################################################################
# RUN GENERATOR
###############################################################################

echo "Running generator..."

"$VENV_DIR/bin/python" "$PYTHON_SCRIPT"

###############################################################################
# DONE
###############################################################################

echo ""
echo "Done."
echo ""
echo "Restart Steam."
